export function getInventory() {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored) {
      const parsed = JSON.parse(stored);
      if (Array.isArray(parsed) && parsed.length > 0) {
        // Enforce strict uniqueness to prevent duplicate rows
        const seen = new Set();
        const deduplicated = [];
        for (const item of parsed) {
          const key = `${item.id || ''}_${item.tagCode || ''}_${item.name || ''}`;
          if (!seen.has(key)) {
            seen.add(key);
            deduplicated.push(item);
          }
        }
        return deduplicated;
      }
    }
  } catch (e) {
    console.warn('Failed to load inventory from localStorage', e);
  }
  return DEFAULT_EQUIPMENT_ITEMS;
}

export function setInventory(items) {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(items));
  } catch (e) {
    console.warn('Failed to save inventory to localStorage', e);
  }
}

export function addInventoryItem(item) {
  const items = getInventory();
  const newItem = {
    ...item,
    id: item.id || ('item-' + Date.now() + '-' + Math.random().toString(36).substr(2, 4))
  };
  const updated = [newItem, ...items];
  setInventory(updated);
  return newItem;
}

export function updateInventoryItem(id, updatedFields) {
  const items = getInventory();
  const updated = items.map((i) => (i.id === id ? { ...i, ...updatedFields } : i));
  setInventory(updated);
  return updated;
}

export function deleteInventoryItem(id) {
  const items = getInventory();
  const updated = items.filter((i) => i.id !== id);
  setInventory(updated);
  return updated;
}

